#!/usr/bin/env python3
"""Original Clarice monochrome Finder artwork; no external artwork or fonts."""
from pathlib import Path
import struct, zlib
root = Path(__file__).resolve().parents[1]
out = root / 'outputs/namespace'
out.mkdir(parents=True, exist_ok=True)

def artwork(size):
    bits = [[0] * size for _ in range(size)]
    mask = [[0] * size for _ in range(size)]
    def rect(x0,y0,x1,y1,fill=1):
        for y in range(y0,y1+1):
            for x in range(x0,x1+1): bits[y][x]=fill
    if size == 32:
        # Window, title bar, output lines, chevron and full block cursor.
        rect(2,4,28,27); rect(3,5,27,26,0)
        rect(4,8,26,8); rect(5,6,7,6); rect(11,6,25,6)
        rect(6,12,21,12); rect(6,15,16,15)
        for x,y in [(6,19),(7,20),(8,21),(7,22),(6,23)]: rect(x,y,x+1,y)
        rect(12,19,16,24)
        rect(29,6,29,28); rect(4,28,29,28)
        bounds=(2,4,29,28)
    else:
        rect(0,2,14,13); rect(1,3,13,12,0)
        rect(1,4,13,4); rect(3,6,10,6)
        for x,y in [(3,8),(4,9),(3,10)]: rect(x,y,x,y)
        rect(7,8,9,11);rect(15,4,15,14);rect(2,14,15,14)
        bounds=(0,2,15,14)
    x0,y0,x1,y1=bounds
    for y in range(y0,y1+1):
        for x in range(x0,x1+1): mask[y][x]=1
    return bits,mask

def packed(rows):
    return b''.join(int(''.join(map(str,row)),2).to_bytes(len(row)//8,'big') for row in rows)

resources=['/* Original Clarice command-window artwork. Generated by scripts/make-icon.py. */',
'''data 'BNDL' (128) { "CLRC" $"0000 0001" "FREF" $"0000 0000 0080" "ICN#" $"0000 0000 0080" };
data 'FREF' (128) { "APPL" $"0000 00" };
data 'CLRC' (0) { $"07" "Clarice" };''']
for size,kind in [(32,'ICN#'),(16,'ics#')]:
    bits,mask=artwork(size);data=packed(bits)+packed(mask)
    resources.append("data '%s' (128) {\n%s\n};" % (kind,'\n'.join(' $"'+data[i:i+16].hex().upper()+'"' for i in range(0,len(data),16))))
(root/'src/Icons.r').write_text('\n'.join(resources)+'\n')
# Magnified nearest-neighbour preview, using exactly the resource pixels.
bits,_=artwork(32); scale=8; width=32*scale
raw=b''.join(b'\0'+bytes(0 if bits[y//scale][x//scale] else 255 for x in range(width)) for y in range(width))
def chunk(kind,data):
    return struct.pack('>I',len(data))+kind+data+struct.pack('>I',zlib.crc32(kind+data)&0xffffffff)
png=b'\x89PNG\r\n\x1a\n'+chunk(b'IHDR',struct.pack('>IIBBBBB',width,width,8,0,0,0,0))+chunk(b'IDAT',zlib.compress(raw))+chunk(b'IEND',b'')
(out/'clarice-icon.png').write_bytes(png)
print('Wrote native 32/16 pixel icon resources and preview.')
